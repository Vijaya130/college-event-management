    B.Book_id,
    B.Title,
    B.Publisher_Name,
    BA.Author_Name,
    BC.Programme_id,
    BC.No_of_Copies
FROM BOOK B
JOIN BOOK_AUTHORS BA ON B.Book_id = BA.Book_id
JOIN BOOK_COPIES BC ON B.Book_id = BC.Book_id;

