CREATE VIEW Available_Books AS
SELECT 
    B.Book_id,
    B.Title,
    SUM(BC.No_of_Copies) AS Total_Copies
FROM BOOK B
JOIN BOOK_COPIES BC ON B.Book_id = BC.Book_id
GROUP BY B.Book_id, B.Title;
SELECT * FROM Available_Books;